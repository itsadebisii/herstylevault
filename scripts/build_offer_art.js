/* Builds offers-art.js: the line-art garments used on the service and package cover pictures.
   They come from the quiz's drawings (color-style-analysis.html), recolored to the brand burgundy.
       node scripts/build_offer_art.js                                                          */
const fs = require('fs'), path = require('path');
const src = fs.readFileSync(path.join(__dirname, '..', 'color-style-analysis.html'), 'utf8');
const all = JSON.parse(src.match(/const ART_ICONS = (\{.*\});/)[1]);
const keep = ['blazer', 'coat', 'dress', 'dressBelted', 'wrap', 'topV', 'trousers', 'bag', 'heel'];
const out = {};
keep.forEach((k) => { out[k] = all[k].replace(/#181716/g, '#7A1321').replace(/ width="100%" height="100%"/, ''); });
fs.writeFileSync(path.join(__dirname, '..', 'offers-art.js'), '/* generated by scripts/build_offer_art.js */\nvar OFFER_ART = ' + JSON.stringify(out) + ';\n');
console.log('wrote offers-art.js', (fs.statSync(path.join(__dirname, '..', 'offers-art.js')).size / 1e3).toFixed(1) + ' KB');
